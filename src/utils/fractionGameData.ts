export function getRandomCustomerOrder(availableFractions: FractionItem[]): CustomerOrder {
  const customer = CUSTOMER_NAMES[Math.floor(Math.random() * CUSTOMER_NAMES.length)];
  const randomFraction = availableFractions[Math.floor(Math.random() * availableFractions.length)];

  return {
    id: `cust_${Date.now()}_${Math.random().toString(36).substring(2, 5)}`,
    customerName: customer.name,
    avatar: customer.avatar,
    requestedFractionId: randomFraction.id,
    bonusMultiplier: 1.4, // Pays 140% of fair value!
    timeLeft: 25,
    maxTime: 25,
  };
}
